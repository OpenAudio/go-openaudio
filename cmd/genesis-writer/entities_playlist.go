type playlistMetadataWrapper struct {
	CID  string                `json:"cid"`
	Data playlistMetadataInner `json:"data"`
}

type playlistMetadataInner struct {
	CreatedAt              string      `json:"created_at,omitempty"`
	PlaylistName           string      `json:"playlist_name"`
	Description            string      `json:"description,omitempty"`
	IsAlbum                bool        `json:"is_album,omitempty"`
	IsPrivate              bool        `json:"is_private,omitempty"`
	IsImageAutogenerated   bool        `json:"is_image_autogenerated,omitempty"`
	PlaylistImageSizesHash string      `json:"playlist_image_sizes_multihash,omitempty"`
	PlaylistContents       interface{} `json:"playlist_contents,omitempty"`
	ReleaseDate            string      `json:"release_date,omitempty"`
	IsScheduledRelease     bool        `json:"is_scheduled_release,omitempty"`
	IsStreamGated          bool        `json:"is_stream_gated,omitempty"`
	StreamConditions       interface{} `json:"stream_conditions,omitempty"`
	UPC                    string      `json:"upc,omitempty"`
	PlaylistImageHash      string      `json:"playlist_image_multihash,omitempty"`
	DDEXApp                string      `json:"ddex_app,omitempty"`
	ParentalWarningType    string      `json:"parental_warning_type,omitempty"`
	DDEXReleaseIDs         interface{} `json:"ddex_release_ids,omitempty"`
	Artists                interface{} `json:"artists,omitempty"`
	CopyrightLine          interface{} `json:"copyright_line,omitempty"`
	ProducerCopyright      interface{} `json:"producer_copyright_line,omitempty"`
	// The route the playlist serves today. Carried rather than regenerated:
	// see playlistState.Route in the indexer for the measurements.
	RouteSlug        string `json:"route_slug,omitempty"`
	RouteTitleSlug   string `json:"route_title_slug,omitempty"`
	RouteCollisionID int    `json:"route_collision_id,omitempty"`
	// The playlist's removal history: tracks that were once in it and have
	// since left, one entry per source playlist_tracks row with
	// is_removed = true. Carried rather than derived, because a Create replays
	// a snapshot and the indexer only recognizes a removal as a transition
	// between two states — see insertPlaylistTrackTombstones. Empty for the
	// 308,635 of 312,552 playlists that never lost a track.
	RemovedTracks []removedPlaylistTrack `json:"removed_tracks,omitempty"`
	// Always serialized: `omitempty` would drop a false value and the indexer
	// cannot tell "absent" from "false".
	IsDelete bool `json:"is_delete"`
}

// removedPlaylistTrack is one tombstone in a playlist's removal history.
// created_at is when the track joined the playlist, updated_at when it left —
// the latter is the timestamp the API compares against a purchase date to
// decide whether an album buyer still has access to a track that has since left
// the album, so it is carried verbatim rather than stamped at replay time.
type removedPlaylistTrack struct {
	TrackID   int64  `json:"track_id"`
	CreatedAt string `json:"created_at"`
	UpdatedAt string `json:"updated_at"`
}

// preloadRemovedPlaylistTracks loads every tombstone in the source, keyed by
// playlist. Small enough to hold in memory: 24,579 rows over 4,064 playlists on
// a production clone.
func preloadRemovedPlaylistTracks(ctx context.Context, db *pgxpool.Pool) (map[int64][]removedPlaylistTrack, error) {
	rows, err := db.Query(ctx, `
		SELECT playlist_id, track_id, created_at, updated_at
		FROM playlist_tracks
		WHERE is_removed = true
		ORDER BY playlist_id, updated_at, track_id`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	m := make(map[int64][]removedPlaylistTrack)
	for rows.Next() {
		var playlistID int64
		var r removedPlaylistTrack
		var createdAt, updatedAt time.Time
		if err := rows.Scan(&playlistID, &r.TrackID, &createdAt, &updatedAt); err != nil {
			return nil, err
		}
		r.CreatedAt = createdAt.UTC().Format(time.RFC3339Nano)
		r.UpdatedAt = updatedAt.UTC().Format(time.RFC3339Nano)
		m[playlistID] = append(m[playlistID], r)
	}
	return m, rows.Err()
}

type sourcePlaylist struct {
	PlaylistID           int64
	PlaylistOwnerID      int64
	OwnerWallet          string
	PlaylistName         *string
	Description          *string
	IsAlbum              bool
	IsPrivate            bool
	IsImageAutogenerated bool
	MetadataMultihash    *string
	ImageSizesMultihash  *string
	ImageMultihash       *string
	PlaylistContents     []byte // JSONB
	UPC                  *string
	DDEXApp              *string
	ParentalWarningType  *string
	ReleaseDate          *time.Time
	IsScheduledRelease   bool
	IsStreamGated        bool
	StreamConditions     []byte // JSONB
	DDEXReleaseIDs       []byte // JSONB
	Artists              []byte // JSONB
	CopyrightLine        []byte // JSONB
	ProducerCopyright    []byte // JSONB
	RouteSlug            *string
	RouteTitleSlug       *string
	RouteCollisionID     *int
	IsDelete             bool
	CreatedAt            time.Time
}

func (w *Writer) writePlaylists(ctx context.Context) error {
	// Pre-load the removal history. It lives in playlist_tracks, not in the
	// playlist row, and a Create carrying only the final contents would lose it
	// entirely.
	removedTracks, err := preloadRemovedPlaylistTracks(ctx, w.srcDB)
	if err != nil {
		return fmt.Errorf("preload removed playlist tracks: %w", err)
	}

	return processBatched(ctx, w, "playlists",
		// Deleted playlists are migrated too, carrying is_delete in the metadata, so
		// a parity check can tell an intentional omission from real data loss.
		`SELECT count(*) FROM playlists p
		JOIN users u ON u.user_id = p.playlist_owner_id AND u.is_current = true AND u.wallet IS NOT NULL AND u.wallet <> ''
		WHERE p.is_current = true`,
		`SELECT
			p.playlist_id, p.playlist_owner_id, COALESCE(LOWER(u.wallet), ''),
			p.playlist_name, p.description,
			p.is_album, p.is_private, p.is_image_autogenerated,
			p.metadata_multihash, p.playlist_image_sizes_multihash, p.playlist_image_multihash, p.playlist_contents,
			p.upc, p.ddex_app, p.parental_warning_type,
			p.release_date, p.is_scheduled_release, p.is_stream_gated, p.stream_conditions,
			p.ddex_release_ids, p.artists, p.copyright_line, p.producer_copyright_line,
			r.slug, r.title_slug, r.collision_id,
			p.is_delete,
			p.created_at
		FROM playlists p
		JOIN users u ON u.user_id = p.playlist_owner_id AND u.is_current = true AND u.wallet IS NOT NULL AND u.wallet <> ''
		LEFT JOIN LATERAL (
			SELECT slug, title_slug, collision_id
			FROM playlist_routes pr
			WHERE pr.playlist_id = p.playlist_id AND pr.is_current = true
			ORDER BY pr.collision_id DESC, pr.slug
			LIMIT 1
		) r ON true
		WHERE p.is_current = true
		ORDER BY p.playlist_id`,
		func(rows pgx.Rows) (sourcePlaylist, error) {
			var p sourcePlaylist
			err := rows.Scan(
				&p.PlaylistID, &p.PlaylistOwnerID, &p.OwnerWallet,
				&p.PlaylistName, &p.Description,
				&p.IsAlbum, &p.IsPrivate, &p.IsImageAutogenerated,
				&p.MetadataMultihash, &p.ImageSizesMultihash, &p.ImageMultihash, &p.PlaylistContents,
				&p.UPC, &p.DDEXApp, &p.ParentalWarningType,
				&p.ReleaseDate, &p.IsScheduledRelease, &p.IsStreamGated, &p.StreamConditions,
				&p.DDEXReleaseIDs, &p.Artists, &p.CopyrightLine, &p.ProducerCopyright,
				&p.RouteSlug, &p.RouteTitleSlug, &p.RouteCollisionID,
				&p.IsDelete,
				&p.CreatedAt,
			)
			return p, err
		},
		func(ctx context.Context, p sourcePlaylist) error {
			inner := playlistMetadataInner{
				CreatedAt:              p.CreatedAt.UTC().Format(time.RFC3339Nano),
				PlaylistName:           deref(p.PlaylistName),
				Description:            deref(p.Description),
				IsAlbum:                p.IsAlbum,
				IsPrivate:              p.IsPrivate,
				IsImageAutogenerated:   p.IsImageAutogenerated,
				PlaylistImageSizesHash: deref(p.ImageSizesMultihash),
				PlaylistImageHash:      deref(p.ImageMultihash),
				UPC:                    deref(p.UPC),
				DDEXApp:                deref(p.DDEXApp),
				ParentalWarningType:    deref(p.ParentalWarningType),
				ReleaseDate:            fmtReleaseDate(p.ReleaseDate),
				IsScheduledRelease:     p.IsScheduledRelease,
				IsStreamGated:          p.IsStreamGated,
				RouteSlug:              deref(p.RouteSlug),
				RouteTitleSlug:         deref(p.RouteTitleSlug),
				RouteCollisionID:       derefInt(p.RouteCollisionID),
				IsDelete:               p.IsDelete,
				RemovedTracks:          removedTracks[p.PlaylistID],
			}

			inner.PlaylistContents = unmarshalJSONB(p.PlaylistContents)
			inner.StreamConditions = unmarshalJSONB(p.StreamConditions)
			inner.DDEXReleaseIDs = unmarshalJSONB(p.DDEXReleaseIDs)
			inner.Artists = unmarshalJSONB(p.Artists)
			inner.CopyrightLine = unmarshalJSONB(p.CopyrightLine)
			inner.ProducerCopyright = unmarshalJSONB(p.ProducerCopyright)

			cid := "genesis-import"
			if p.MetadataMultihash != nil && *p.MetadataMultihash != "" {
				cid = *p.MetadataMultihash
			}

			metaJSON, err := json.Marshal(playlistMetadataWrapper{
				CID:  cid,
				Data: inner,
			})
			if err != nil {
				return fmt.Errorf("marshal playlist %d metadata: %w", p.PlaylistID, err)
			}
			return w.addManageEntityWithSigner(ctx, &corev1.ManageEntityLegacy{
				UserId:     p.PlaylistOwnerID,
				EntityType: "Playlist",
				EntityId:   p.PlaylistID,
				Action:     "Create",
				Metadata:   string(metaJSON),
			}, p.OwnerWallet)
		},
	)
}
