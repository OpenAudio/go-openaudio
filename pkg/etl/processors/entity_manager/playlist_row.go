// playlistRow holds columns we read/write for playlist create/update parity.
type playlistRow struct {
	PlaylistID                  int64
	PlaylistOwnerID             int64
	PlaylistName                *string
	Description                 *string
	IsAlbum                     bool
	IsPrivate                   bool
	PlaylistContents            []byte
	PlaylistImageMultihash      *string
	PlaylistImageSizesMultihash *string
	IsImageAutogenerated        bool
	IsStreamGated               bool
	StreamConditions            []byte
	IsScheduledRelease          bool
	ReleaseDate                 pgtype.Timestamp
	UPC                         *string
	DdexApp                     *string
	DdexReleaseIDs              []byte
	Artists                     []byte
	CopyrightLine               []byte
	ProducerCopyrightLine       []byte
	ParentalWarningType         *string
	IsAvailable                 bool
	LastAddedTo                 pgtype.Timestamp
	CreatedAt                   time.Time
}

func loadCurrentPlaylistRow(ctx context.Context, dbtx db.DBTX, playlistID int64) (*playlistRow, error) {
	var r playlistRow
	var name, desc, imgHash, imgSizes, upc, ddex, parentalWarning sql.NullString
	var contents, streamCond, ddexRel, artists, copyright, producerCopyright []byte
	var releaseDate pgtype.Timestamp

	err := dbtx.QueryRow(ctx, `
		SELECT playlist_id, playlist_owner_id, playlist_name, description,
			is_album, is_private, playlist_contents,
			playlist_image_multihash, playlist_image_sizes_multihash, is_image_autogenerated,
			is_stream_gated, stream_conditions, is_scheduled_release, release_date,
			upc, ddex_app, ddex_release_ids, artists, copyright_line, producer_copyright_line,
			parental_warning_type, last_added_to, created_at
		FROM playlists WHERE playlist_id = $1 AND is_current = true AND is_delete = false LIMIT 1
	`, playlistID).Scan(
		&r.PlaylistID, &r.PlaylistOwnerID, &name, &desc,
		&r.IsAlbum, &r.IsPrivate, &contents,
		&imgHash, &imgSizes, &r.IsImageAutogenerated,
		&r.IsStreamGated, &streamCond, &r.IsScheduledRelease, &releaseDate,
		&upc, &ddex, &ddexRel, &artists, &copyright, &producerCopyright,
		&parentalWarning, &r.LastAddedTo, &r.CreatedAt,
	)
	if errors.Is(err, pgx.ErrNoRows) {
		// Same race as loadCurrentTrackRow: validation accepts is_delete=true
		// rows but this loader filters them out. Convert to ValidationError.
		return nil, NewValidationError("playlist %d is deleted or does not exist", playlistID)
	}
	if err != nil {
		return nil, err
	}
	r.PlaylistName = nullStrPtr(name)
	r.Description = nullStrPtr(desc)
	r.PlaylistContents = contents
	if len(r.PlaylistContents) == 0 {
		r.PlaylistContents = []byte("{}")
	}
	r.PlaylistImageMultihash = nullStrPtr(imgHash)
	r.PlaylistImageSizesMultihash = nullStrPtr(imgSizes)
	r.StreamConditions = streamCond
	r.ReleaseDate = releaseDate
	r.UPC = nullStrPtr(upc)
	r.DdexApp = nullStrPtr(ddex)
	r.DdexReleaseIDs = ddexRel
	r.Artists = artists
	r.CopyrightLine = copyright
	r.ProducerCopyrightLine = producerCopyright
	r.ParentalWarningType = nullStrPtr(parentalWarning)
	return &r, nil
}

// mergePlaylistFromMetadata applies metadata onto a copy of row for an update.
func mergePlaylistFromMetadata(p *Params, base *playlistRow) *playlistRow {
	out := *base

	mergeStrPtr := func(metaKey string, cur **string) {
		if _, ok := p.Metadata[metaKey]; !ok {
			return
		}
		s := p.MetadataString(metaKey)
		if s == "" {
			*cur = nil
		} else {
			cp := s
			*cur = &cp
		}
	}

	mergeStrPtr("playlist_name", &out.PlaylistName)
	mergeStrPtr("description", &out.Description)
	mergeStrPtr("playlist_image_multihash", &out.PlaylistImageMultihash)
	mergeStrPtr("playlist_image_sizes_multihash", &out.PlaylistImageSizesMultihash)
	mergeStrPtr("upc", &out.UPC)
	mergeStrPtr("ddex_app", &out.DdexApp)
	mergeStrPtr("parental_warning_type", &out.ParentalWarningType)

	if v, ok := p.MetadataBool("is_album"); ok {
		out.IsAlbum = v
	}
	if v, ok := p.MetadataBool("is_private"); ok {
		out.IsPrivate = v
	}
	if v, ok := p.MetadataBool("is_image_autogenerated"); ok {
		out.IsImageAutogenerated = v
	}
	if v, ok := p.MetadataBool("is_stream_gated"); ok {
		out.IsStreamGated = v
	}
	if v, ok := p.MetadataBool("is_scheduled_release"); ok {
		out.IsScheduledRelease = v
	}

	// playlist_contents: present when the metadata key exists, including the
	// SDK-sent empty list `[]`. Normalize to `{"track_ids":[...]}` regardless
	// of whether the SDK sent the legacy dict or the new bare-array shape so
	// downstream readers see one schema.
	if _, ok := p.Metadata["playlist_contents"]; ok {
		out.PlaylistContents = normalizePlaylistContentsJSON(p.Metadata)
	}
	if v, ok := p.MetadataJSON("stream_conditions"); ok {
		out.StreamConditions = marshalJSONOrNil(v)
	}
	if v, ok := p.MetadataJSON("ddex_release_ids"); ok {
		out.DdexReleaseIDs = marshalJSONOrNil(v)
	}
	if v, ok := p.MetadataJSON("artists"); ok {
		out.Artists = marshalJSONOrNil(v)
	}
	if v, ok := p.MetadataJSON("copyright_line"); ok {
		out.CopyrightLine = marshalJSONOrNil(v)
	}
	if v, ok := p.MetadataJSON("producer_copyright_line"); ok {
		out.ProducerCopyrightLine = marshalJSONOrNil(v)
	}

	if rd, ok := parseReleaseDate(p.MetadataString("release_date")); ok {
		out.ReleaseDate = rd
	}

	return &out
}

